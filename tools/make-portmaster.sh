#!/bin/sh
# Builds a PortMaster port for one game: copy the out dir's contents into the handheld's ports
# folder (where the other ports' .sh files are, e.g. /roms/ports) and the game shows up there.
#
#   tools/make-portmaster.sh "/path/to/game folder" ["Title"] [out dir]
#   tools/make-portmaster.sh --list [out dir]    one "gmRunner" port with a game list instead: games
#                                                 go in gmrunner/games/ on the device
#
# Writes (default out dir: dist/portmaster/ports):
#   <Title>.sh                    the launcher PortMaster lists
#   gmrunner/gmrunner.aarch64     the runner (shared by every game made this way)
#   gmrunner/games/<Title>/       the game's files (everything except the Windows .exe/.dll)
#   gmrunner/saves/<Title>/       created on first run
# The runner itself comes from tools/portmaster/build.sh.
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
bin="$root/dist/portmaster/gmrunner.aarch64"
[ -f "$bin" ] || { echo "build the runner first: tools/portmaster/build.sh" >&2; exit 1; }

if [ "${1:-}" = --list ]; then
    list=1
    out="${2:-dist/portmaster/ports}"
    folder=gmRunner
    mkdir -p "$out/gmrunner/games"
    printf '%s\n' "Copy each game's folder (the one with data.win or game.unx) here." > "$out/gmrunner/games/README.txt"
else
    list=0
    game="${1:?usage: make-portmaster.sh <game dir> [title] [out dir] | --list [out dir]}"
    title="${2:-$(basename "$game")}"
    out="${3:-dist/portmaster/ports}"
    [ -f "$game/data.win" ] || [ -f "$game/game.unx" ] || [ -f "$game/assets/game.unx" ] ||
        { echo "no data.win in $game" >&2; exit 1; }
    # Folder and file names stay plain ASCII without quotes; FAT32/exFAT cards and the
    # frontends' launch scripts are happier that way.
    folder="$(printf '%s' "$title" | tr -cd 'A-Za-z0-9 ._-')"
    [ -n "$folder" ] || folder="Game"
    mkdir -p "$out/gmrunner/games/$folder"
    for f in "$game"/*; do
        case "$f" in
            *.exe|*.dll|*.EXE|*.DLL) ;;
            *) cp -R "$f" "$out/gmrunner/games/$folder/" ;;
        esac
    done
fi
cp "$bin" "$out/gmrunner/gmrunner.aarch64"
chmod +x "$out/gmrunner/gmrunner.aarch64"

# gmRunner's license and those of the third-party software in it (SDL2 itself comes from the device;
# FFmpeg is linked in, LGPL).
mkdir -p "$out/gmrunner/licenses"
cp "$root/licenses/GPL-3.0.txt" "$root/licenses/stb.txt" "$root/licenses/liberation-fonts.txt" "$root/licenses/SDL2.txt" \
    "$root/licenses/bzip2.txt" "$root/licenses/ffmpeg.txt" "$root/licenses/LGPL-2.1.txt" \
    "$root/licenses/gamemaker-html5.txt" "$root/licenses/Apache-2.0.txt" "$out/gmrunner/licenses/"

# The launcher, in the shape every PortMaster port uses: find PortMaster's control.txt (it sets
# $directory, $GPTOKEYB, the device's SDL controller mapping, ...), log to the port folder, run.
launcher="$out/$folder.sh"
cat > "$launcher" <<'EOF'
#!/bin/bash
# PORTMASTER: gmrunner, GameMaker game launcher (generated by gmrunner's tools/make-portmaster.sh)

XDG_DATA_HOME=${XDG_DATA_HOME:-$HOME/.local/share}
if [ -d "/opt/system/Tools/PortMaster/" ]; then
  controlfolder="/opt/system/Tools/PortMaster"
elif [ -d "/opt/tools/PortMaster/" ]; then
  controlfolder="/opt/tools/PortMaster"
elif [ -d "$XDG_DATA_HOME/PortMaster/" ]; then
  controlfolder="$XDG_DATA_HOME/PortMaster"
else
  controlfolder="/roms/ports/PortMaster"
fi

source $controlfolder/control.txt
[ -f "${controlfolder}/mod_${CFW_NAME}.txt" ] && source "${controlfolder}/mod_${CFW_NAME}.txt"
get_controls

GAMEDIR="/$directory/ports/gmrunner"
GAME="@GAME@"
cd "$GAMEDIR"
> "$GAMEDIR/log.txt" && exec > >(tee "$GAMEDIR/log.txt") 2>&1

export SDL_GAMECONTROLLERCONFIG="$sdl_controllerconfig"
chmod +x "$GAMEDIR/gmrunner.aarch64"

# gptokeyb only watches for PortMaster's quit hotkey; the runner reads the controller itself
# (Start + Select also quits).
$GPTOKEYB "gmrunner.aarch64" &
[ "$(type -t pm_platform_helper)" = function ] && pm_platform_helper "$GAMEDIR/gmrunner.aarch64"
@RUN@

[ "$(type -t pm_finish)" = function ] && pm_finish
$ESUDO kill -9 $(pidof gptokeyb) 2>/dev/null
printf "\033c" > /dev/tty1
EOF
# What it runs: the one game, or the game list (each game's saves under saves/gmrunner/<game>),
# then the game folder name (sed: titles may hold characters the shell would expand).
if [ "$list" = 1 ]; then
    run='XDG_DATA_HOME="$GAMEDIR/saves" ./gmrunner.aarch64 --picker "$GAMEDIR/games"'
else
    run='./gmrunner.aarch64 "$GAMEDIR/games/$GAME" --save-dir "$GAMEDIR/saves/$GAME"'
fi
awk -v run="$run" '{ if ($0 == "@RUN@") print run; else print }' "$launcher" | sed "s|@GAME@|$folder|" > "$launcher.tmp"
mv "$launcher.tmp" "$launcher"
chmod +x "$launcher"

echo "built $launcher"
echo "      $out/gmrunner/games/$([ "$list" = 1 ] || echo "$folder/") ($(du -sh "$out/gmrunner/games" | cut -f1))"
echo "copy the contents of $out into the handheld's ports folder"
